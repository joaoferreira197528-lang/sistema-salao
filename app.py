import streamlit as st
import pandas as pd
import sqlite3
from datetime import datetime

# ==========================================
# 1. CONFIGURAÇÃO DA PÁGINA E BANCO DE DADOS
# ==========================================
st.set_page_config(page_title="Gestão Salão", layout="wide", page_icon="💇‍♀️")

def init_db():
    """Inicializa o banco de dados local SQLite e cria as tabelas se não existirem."""
    with sqlite3.connect('salao.db') as conn:
        cursor = conn.cursor()
        # Tabela de Estoque
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS estoque (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                produto TEXT NOT NULL,
                quantidade INTEGER NOT NULL,
                preco_venda REAL NOT NULL,
                min_critico INTEGER NOT NULL
            )
        ''')
        # Tabela de Fluxo de Caixa
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS fluxo_caixa (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                data TEXT DEFAULT (date('now')),
                tipo TEXT CHECK(tipo IN ('Entrada', 'Saída')),
                categoria TEXT NOT NULL,
                descricao TEXT,
                valor REAL NOT NULL
            )
        ''')
        conn.commit()

# Funções auxiliares para interagir com o SQLite usando Pandas
def query_db(sql, params=()):
    with sqlite3.connect('salao.db') as conn:
        return pd.read_sql_query(sql, conn, params=params)

def execute_db(sql, params=()):
    with sqlite3.connect('salao.db') as conn:
        conn.execute(sql, params)
        conn.commit()

# Garante a criação do banco ao iniciar o script
init_db()

# ==========================================
# 2. INTERFACE E NAVEGAÇÃO
# ==========================================
st.title("💇‍♀️ Sistema de Gestão - Estoque & Caixa")

# Menu de navegação lateral
aba = st.sidebar.radio("Ir para:", ["Painel Geral", "Estoque", "Fluxo de Caixa"])

# --- ABA 1: PAINEL GERAL ---
if aba == "Painel Geral":
    st.subheader("📊 Resumo Financeiro e Alertas")

    # Busca movimentações de caixa para calcular os indicadores principais
    df_caixa = query_db("SELECT tipo, valor FROM fluxo_caixa")
    if not df_caixa.empty:
        entradas = df_caixa[df_caixa['tipo'] == 'Entrada']['valor'].sum()
        saidas = df_caixa[df_caixa['tipo'] == 'Saída']['valor'].sum()
        saldo = entradas - saidas
    else:
        entradas, saidas, saldo = 0.0, 0.0, 0.0

    # Linha de métricas financeiras
    col1, col2, col3 = st.columns(3)
    col1.metric("Total Entradas", f"R$ {entradas:.2f}")
    col2.metric("Total Saídas", f"R$ {saidas:.2f}", delta_color="inverse")
    col3.metric("Saldo Atual", f"R$ {saldo:.2f}")

    st.write("---")

    # Alertas de Estoque Crítico
    df_estoque = query_db("SELECT produto, quantidade, min_critico FROM estoque")
    if not df_estoque.empty:
        # Filtra produtos onde a quantidade em estoque é menor ou igual ao mínimo crítico definido
        itens_criticos = df_estoque[df_estoque['quantidade'] <= df_estoque['min_critico']]
        if not itens_criticos.empty:
            st.warning("⚠️ **Alerta de Reposição Instantânea:** Os itens abaixo atingiram o nível crítico!")
            st.dataframe(itens_criticos, hide_index=True, use_container_width=True)
        else:
            st.success("✅ Todos os produtos estão com níveis estáveis em estoque.")
    else:
        st.info("Nenhum produto cadastrado no inventário ainda.")

# --- ABA 2: GESTÃO DE ESTOQUE ---
elif aba == "Estoque":
    st.subheader("📦 Controle de Produtos")

    # Dividindo a tela: Cadastro à esquerda, Entrada rápida à direita
    col_cad, col_venda = st.columns(2)

    with col_cad:
        with st.expander("➕ Cadastrar Novo Produto", expanded=True):
            novo_nome = st.text_input("Nome do Produto")
            nova_qtd = st.number_input("Quantidade Inicial", min_value=0, step=1, value=0)
            preco_venda = st.number_input("Preço Unitário de Venda (R$)", min_value=0.0, format="%.2f", value=0.0)
            min_critico = st.number_input("Quantidade Mínima de Alerta", min_value=0, step=1, value=2)

            if st.button("Salvar Produto"):
                if novo_nome:
                    execute_db(
                        "INSERT INTO estoque (produto, quantidade, preco_venda, min_critico) VALUES (?, ?, ?, ?)",
                        (novo_nome, nova_qtd, preco_venda, min_critico)
                    )
                    st.success(f"'{novo_nome}' adicionado ao inventário!")
                    st.rerun()
                else:
                    st.error("Por favor, digite o nome do produto.")

    with col_venda:
        with st.expander("🛒 Registrar Venda (Baixa de Estoque -> Entrada de Caixa)", expanded=True):
            df_produtos = query_db("SELECT id, produto, quantidade, preco_venda FROM estoque WHERE quantidade > 0")
            if not df_produtos.empty:
                prod_selecionado = st.selectbox("Escolha o produto vendido", df_produtos['produto'])
                qtd_venda = st.number_input("Quantidade vendida", min_value=1, step=1, value=1)

                # Extrai informações do produto selecionado
                prod_info = df_produtos[df_produtos['produto'] == prod_selecionado].iloc[0]

                if st.button("Confirmar Venda"):
                    if qtd_venda <= prod_info['quantidade']:
                        valor_total = prod_info['preco_venda'] * qtd_venda

                        # 1. Deduz a quantidade vendida do estoque
                        execute_db("UPDATE estoque SET quantidade = quantidade - ? WHERE id = ?", (qtd_venda, int(prod_info['id'])))

                        # 2. Registra automaticamente a Entrada financeira no fluxo de caixa
                        execute_db(
                            "INSERT INTO fluxo_caixa (tipo, categoria, descricao, valor) VALUES ('Entrada', 'Venda de Produto', ?, ?)",
                            (f"Venda: {qtd_venda}x {prod_selecionado}", valor_total)
                        )
                        st.success(f"Venda concluída! R$ {valor_total:.2f} lançados no fluxo de caixa.")
                        st.rerun()
                    else:
                        st.error(f"Estoque insuficiente! Você só tem {prod_info['quantidade']} unidades disponíveis.")
            else:
                st.info("Nenhum item com estoque disponível para realizar vendas no momento.")

    st.write("### Inventário Atual")
    df_inventario = query_db("SELECT id AS 'Código', produto AS 'Produto', quantidade AS 'Quantidade', preco_venda AS 'Preço de Venda (R$)', min_critico AS 'Mínimo Crítico' FROM estoque")
    st.dataframe(df_inventario, use_container_width=True, hide_index=True)

# --- ABA 3: FLUXO DE CAIXA ---
elif aba == "Fluxo de Caixa":
    st.subheader("💸 Movimentações Financeiras")

    col_form, col_lista = st.columns([1, 2])

    with col_form:
        st.write("### Lançamento Manual")
        tipo = st.selectbox("Tipo de Operação", ["Entrada", "Saída"])
        categoria = st.selectbox("Categoria", ["Serviço", "Venda de Produto", "Aluguel/Estrutura", "Produtos/Insumos", "Marketing", "Outros"])
        descricao = st.text_input("Descrição / Detalhes")
        valor = st.number_input("Valor da Transação (R$)", min_value=0.0, format="%.2f", value=0.0)

        if st.button("Registrar Transação"):
            if valor > 0:
                execute_db("INSERT INTO fluxo_caixa (tipo, categoria, descricao, valor) VALUES (?, ?, ?, ?)",
                           (tipo, categoria, descricao, valor))
                st.success("Transação financeira armazenada com sucesso!")
                st.rerun()
            else:
                st.error("O valor inserido precisa ser maior que zero.")

    with col_lista:
        st.write("### Histórico de Transações")
        df_historico = query_db("SELECT data AS 'Data', tipo AS 'Tipo', categoria AS 'Categoria', descricao AS 'Descrição', valor AS 'Valor (R$)' FROM fluxo_caixa ORDER BY id DESC")
        st.dataframe(df_historico, use_container_width=True, hide_index=True)

        # Inserção do Gráfico Analítico de Caixa
        if not df_historico.empty:
            st.write("---")
            st.write("### 📊 Total Financeiro Movimentado por Categoria")
            # Agrupa os valores da coluna 'Valor (R$)' usando a coluna 'Categoria' como índice
            df_agrupado = df_historico.groupby('Categoria')['Valor (R$)'].sum()
            # Renderiza o gráfico de barras interativo nativo do Streamlit
            st.bar_chart(df_agrupado)